"""Generate platform token files from design/tokens.json.

    python3 design/build_tokens.py

Writes:
  frontend/src/app/design-tokens.css   (CSS custom properties, light + dark)
  mobile/lib/src/design_tokens.dart    (Dart constants)
Both outputs are generated; edit tokens.json instead.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "design" / "tokens.json").read_text())
HEADER = "GENERATED by design/build_tokens.py from design/tokens.json. Do not edit by hand."


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def css() -> str:
    t = TOKENS
    out = [f"/* {HEADER} */", "", ":root {"]
    for family, scale in t["color"].items():
        for step, hex_ in scale.items():
            out.append(f"  --{family}-{step}: {hex_};")
    for name, hex_ in t["semantic"]["light"].items():
        out.append(f"  --ds-{kebab(name)}: {hex_};")
    for i, hex_ in enumerate(t["chart"], 1):
        out.append(f"  --ds-chart-{i}: {hex_};")
    for k, v in t["space"].items():
        out.append(f"  --ds-space-{k}: {v}px;")
    for k, v in t["radius"].items():
        out.append(f"  --ds-radius-{k}: {v}px;")
    for k, v in t["type"].items():
        out.append(f"  --ds-text-{k}: {v['size']}px;")
    for k, v in t["motion"]["duration"].items():
        out.append(f"  --ds-dur-{k}: {v}ms;")
    for k, v in t["motion"]["easing"].items():
        out.append(f"  --ds-ease-{k}: cubic-bezier({', '.join(str(x) for x in v)});")
    out.append("}")

    dark = [f"  --ds-{kebab(n)}: {h};" for n, h in t["semantic"]["dark"].items()]
    out += ["", "@media (prefers-color-scheme: dark) {",
            '  :root:not(.light):not([data-theme="light"]) {']
    out += ["  " + line for line in dark]
    out += ["  }", "}", '.dark, [data-theme="dark"] {'] + dark + ["}", ""]

    # Users who ask the OS for less motion get instant transitions everywhere.
    out += ["@media (prefers-reduced-motion: reduce) {",
            "  :root { --ds-dur-fast: 0ms; --ds-dur-base: 0ms; --ds-dur-slow: 0ms; --ds-dur-page: 0ms; }",
            "}", ""]
    return "\n".join(out)


def dart_color(hex_: str) -> str:
    return f"Color(0xFF{hex_.lstrip('#').upper()})"


def dart() -> str:
    t = TOKENS
    out = [f"// {HEADER}", "// ignore_for_file: constant_identifier_names", "",
           "import 'dart:ui' show Color;", "", "import 'package:flutter/animation.dart';", ""]

    out.append("/// Raw color scales.")
    out.append("class DSColor {")
    out.append("  DSColor._();")
    for family, scale in t["color"].items():
        for step, hex_ in scale.items():
            out.append(f"  static const {family}{step} = {dart_color(hex_)};")
    out.append("  static const chart = <Color>[")
    out += [f"    {dart_color(h)}," for h in t["chart"]]
    out.append("  ];")
    out.append("}")
    out.append("")

    for mode in ("light", "dark"):
        cls = "DSLight" if mode == "light" else "DSDark"
        out.append(f"/// Semantic colors, {mode} theme.")
        out.append(f"class {cls} {{")
        out.append(f"  {cls}._();")
        for name, hex_ in t["semantic"][mode].items():
            out.append(f"  static const {name} = {dart_color(hex_)};")
        out.append("}")
        out.append("")

    out.append("/// Spacing scale in logical pixels.")
    out.append("class DSSpace {")
    out.append("  DSSpace._();")
    for k, v in t["space"].items():
        out.append(f"  static const double s{k} = {v};")
    out.append("}")
    out.append("")

    out.append("class DSRadius {")
    out.append("  DSRadius._();")
    for k, v in t["radius"].items():
        out.append(f"  static const double {k} = {v};")
    out.append("}")
    out.append("")

    out.append("class DSFont {")
    out.append("  DSFont._();")
    for k, v in t["font"].items():
        out.append(f"  static const {k} = '{v}';")
    out.append("}")
    out.append("")

    out.append("/// Type scale: font size and weight (100-900).")
    out.append("class DSType {")
    out.append("  DSType._();")
    for k, v in t["type"].items():
        out.append(f"  static const double {k}Size = {v['size']};")
        out.append(f"  static const int {k}Weight = {v['weight']};")
        out.append(f"  static const {k}Font = DSFont.{v['font']};")
    out.append("}")
    out.append("")

    out.append("class DSMotion {")
    out.append("  DSMotion._();")
    for k, v in t["motion"]["duration"].items():
        out.append(f"  static const {k} = Duration(milliseconds: {v});")
    for k, v in t["motion"]["easing"].items():
        out.append(f"  static const {k} = Cubic({', '.join(str(x) for x in v)});")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> None:
    targets = {
        ROOT / "frontend" / "src" / "app" / "design-tokens.css": css(),
        ROOT / "mobile" / "lib" / "src" / "design_tokens.dart": dart(),
    }
    for path, text in targets.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
